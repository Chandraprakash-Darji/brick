import { join } from "node:path";

// Post-process `bun run db:schema` output: point the generated schema at the
// single drizzle-orm copy backing `@brickkit/core/pg`. The CLI emits
// `drizzle-orm` / `drizzle-orm/pg-core` imports, which resolve to whichever
// workspace copy the loader finds, while the framework runtime
// (defineDatabase, drizzleAdapter) uses core's copy; mixing the two breaks
// table-type identity (brand symbols) at typecheck and runtime.
//
// The rewrite parses whatever names the CLI emitted and re-emits one sorted
// import, so new builders in future CLI output keep working as long as
// `packages/core/src/db/pg.ts` re-exports them.
const path = join(import.meta.dir, "../src/api/auth/schema.ts");
const generated = await Bun.file(path).text();

const headerPattern =
  /import \{([^}]*)\} from "drizzle-orm";\nimport \{([^}]*)\} from "drizzle-orm\/pg-core";/;
const match = generated.match(headerPattern);
const names = match
  ? `${match[1]},${match[2]}`
      .split(",")
      .map((name) => name.trim())
      .filter(Boolean)
      .filter((name) => name !== "relations")
      .sort()
  : [];
const rewritten = match
  ? generated.replace(
      headerPattern,
      `import { ${names.join(", ")}, defineRelations } from "@brickkit/core/pg";`,
    )
  : generated.replace(/\brelations,/, "defineRelations,");

// Better Auth still generates Drizzle 0.x relation declarations. Convert the
// generated one/many mappings to the single Drizzle 1.x relation definition.
const relationBlocks: { table: string; body: string }[] = [];
const withoutRelations = rewritten.replace(
  /export const \w+Relations = relations\(\s*(\w+),\s*\(\{[^}]*\}\) => \(\{([\s\S]*?)\}\),?\s*\);/g,
  (_, table: string, body: string) => {
    relationBlocks.push({ table, body });
    return "";
  },
);
if (/= relations\(/.test(withoutRelations))
  throw new Error("Unsupported generated Drizzle relation declaration");
const relationTables = [
  ...withoutRelations.matchAll(/export const (\w+) = pgTable\(/g),
].map((match) => match[1]);
const definitions = relationBlocks.map(({ table, body }) => {
  const fields = body
    .replace(
      /one\((\w+),\s*\{\s*fields: \[([^\]]+)\],\s*references: \[([^\]]+)\],?\s*\}\)/g,
      (_, target: string, from: string, to: string) =>
        `r.one.${target}({ from: r.${from.trim()}, to: r.${to.trim()} })`,
    )
    .replace(/many\((\w+)\)/g, "r.many.$1()");
  return `${table}: { ${fields} }`;
});
const withRelations = relationBlocks.length
  ? withoutRelations.trimEnd() +
    `\n\nexport const authRelations = defineRelations({ ${relationTables.join(", ")} }, (r) => ({ ${definitions.join(", ")} }));\n`
  : withoutRelations;

// The CLI occasionally emits a bare `.default()` (no value) that this
// drizzle-orm version rejects at typecheck; it means "no default", so drop it.
const normalized = withRelations.replace(/\.default\(\),/g, ",");
const header = `// GENERATED by \`bun run db:schema\` (better-auth CLI). Do not edit by hand;\n// re-run the script instead. Excluded from oxlint (generated key order).\n`;
const output = normalized.startsWith("// GENERATED")
  ? normalized
  : header + normalized;
await Bun.write(path, output);
console.log("schema imports pointed at @brickkit/core/pg");
