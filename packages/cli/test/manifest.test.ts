import { afterEach, expect, it } from "bun:test";
import { mkdtemp, rm, stat } from "node:fs/promises";
import { join, resolve } from "node:path";
import { renderManifest, scanDefinitionFiles } from "../src/manifest";

const cli = resolve(import.meta.dir, "../src/bin.ts");
const roots: string[] = [];

afterEach(async () => {
  for (const root of roots.splice(0))
    await rm(root, { recursive: true, force: true });
});

async function fixture() {
  const root = await mkdtemp(
    resolve(import.meta.dir, "../.brick-manifest-test-"),
  );
  roots.push(root);
  for (const file of [
    "src/services/orders/orders.service.ts",
    "src/services/orders/orders.events.ts",
    "src/services/orders/actions/get-summary.action.ts",
    "src/services/orders/actions/get-summary.test.ts",
    "src/services/orders/resources/order/order.resource.ts",
    "src/services/orders/resources/order/order.table.ts",
    "src/services/orders/resources/order/commands/ship.command.ts",
    "src/services/orders/workflows/fulfil-order.workflow.ts",
    "src/services/orders/workflows/book-carrier.step.ts",
    "src/services/orders/lib/helpers.ts",
    "src/services/billing/billing.service.ts",
    "src/services/billing/listeners/on-order-shipped.listener.ts",
  ])
    await Bun.write(join(root, file), "export {};\n");
  return root;
}

it("lists definition files: services, then resources, then the rest, by path", async () => {
  const root = await fixture();
  expect(scanDefinitionFiles(join(root, "src/services"))).toEqual([
    "billing/billing.service.ts",
    "orders/orders.service.ts",
    "orders/resources/order/order.resource.ts",
    "billing/listeners/on-order-shipped.listener.ts",
    "orders/actions/get-summary.action.ts",
    "orders/orders.events.ts",
    "orders/resources/order/commands/ship.command.ts",
    "orders/resources/order/order.table.ts",
    "orders/workflows/book-carrier.step.ts",
    "orders/workflows/fulfil-order.workflow.ts",
  ]);
  const source = renderManifest(
    join(root, "src/services"),
    join(root, "_brick"),
  );
  expect(source).toStartWith(
    "// Generated by brick dev, brick build and brick gen. Do not edit.",
  );
  expect(source).toContain(
    'import "../src/services/billing/billing.service";\n',
  );
  expect(source).not.toContain("helpers");
  expect(source).not.toContain(".test");
});

it("brick gen manifest writes services.gen.ts once and keeps it when nothing changed", async () => {
  const root = await fixture();
  const run = () =>
    Bun.spawn([process.execPath, cli, "gen", "manifest"], {
      cwd: root,
      stdout: "pipe",
      stderr: "pipe",
    }).exited;
  expect(await run()).toBe(0);
  const output = join(root, "_brick/services.gen.ts");
  const first = await stat(output);
  await Bun.sleep(20);
  expect(await run()).toBe(0);
  expect((await stat(output)).mtimeMs).toBe(first.mtimeMs);
  await Bun.write(
    join(root, "src/services/billing/actions/refund.action.ts"),
    "export {};\n",
  );
  expect(await run()).toBe(0);
  expect(await Bun.file(output).text()).toContain(
    'import "../src/services/billing/actions/refund.action";',
  );
  // The generated file imports cleanly.
  expect(await import(output)).toBeDefined();
});
