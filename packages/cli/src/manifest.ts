import { existsSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { writeContractSource } from "./client-contract-file";

/** File suffixes of definition files, as in the project structure. */
export const DEFINITION_SUFFIXES = [
  "service",
  "events",
  "resource",
  "table",
  "action",
  "command",
  "tool",
  "socket",
  "listener",
  "workflow",
  "step",
] as const;

export const MANIFEST_FILE = "services.gen.ts";

function rank(file: string) {
  if (/\.service\.[^.]+$/.test(file)) return 0;
  if (/\.resource\.[^.]+$/.test(file)) return 1;
  return 2;
}

/** Definition files under `services`: service files first, then resources, then the rest, each by path. */
export function scanDefinitionFiles(services: string): string[] {
  if (!existsSync(services)) return [];
  // Built per call: index.ts re-exports this module, and Node (ESLint loading
  // brick.config.ts) has no Bun global.
  const glob = new Bun.Glob(
    `**/*.{${DEFINITION_SUFFIXES.join(",")}}.{ts,tsx,mts,js,jsx,mjs}`,
  );
  const files = [...glob.scanSync({ cwd: services, onlyFiles: true })]
    .map((file) => file.split(sep).join("/"))
    .filter((file) => !file.split("/").includes("node_modules"));
  return files.sort(
    (a, b) => rank(a) - rank(b) || (a < b ? -1 : a > b ? 1 : 0),
  );
}

/** The source of `services.gen.ts`, which imports every definition file so each registers itself. */
export function renderManifest(services: string, generated: string): string {
  const imports = scanDefinitionFiles(services).map((file) => {
    let specifier = relative(generated, join(services, file))
      .split(sep)
      .join("/")
      .replace(/\.(ts|tsx|mts|js|jsx|mjs)$/, "");
    if (!specifier.startsWith(".")) specifier = `./${specifier}`;
    return `import ${JSON.stringify(specifier)};\n`;
  });
  return `// Generated by brick dev, brick build and brick gen. Do not edit.
// Imports every definition file under the services folder, so each one
// registers itself on its service. The app entry imports this file.
${imports.join("")}
export {};
`;
}

/** Write `<generated>/services.gen.ts`, leaving it untouched when nothing changed. */
export async function writeServiceManifest(options: {
  services: string;
  generated: string;
}): Promise<string> {
  const output = join(options.generated, MANIFEST_FILE);
  await writeContractSource(
    output,
    renderManifest(options.services, options.generated),
  );
  return output;
}
