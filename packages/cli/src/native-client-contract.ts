import { dirname, relative, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { stat } from "node:fs/promises";
import { isDeepStrictEqual } from "node:util";
import { HttpApi, OpenApi } from "effect/http-api";
import type { NativeBrickApp } from "@brickkit/core";

export async function generateNativeClientContract(
  app: NativeBrickApp,
  options: {
    entry: string;
    output: string;
    load?: (path: string) => Promise<Record<string, unknown>>;
  },
) {
  if (!app.client)
    throw new Error(
      "Brick: configure client.module in Brick.app() with a browser-safe HttpApi export.",
    );
  const base = resolve(dirname(options.entry), app.client.module);
  let modulePath: string | undefined;
  for (const candidate of [
    base,
    base + ".ts",
    base + ".tsx",
    base + ".js",
    base + ".mjs",
    resolve(base, "index.ts"),
  ]) {
    if (
      await stat(candidate).then(
        (value) => value.isFile(),
        (error) => {
          if (error.code === "ENOENT" || error.code === "ENOTDIR") return false;
          throw error;
        },
      )
    ) {
      modulePath = candidate;
      break;
    }
  }
  if (!modulePath)
    throw new Error(
      `Brick: cannot find client contract module '${app.client.module}'.`,
    );
  if (
    resolve(modulePath) === resolve(options.entry) ||
    resolve(modulePath) === resolve(options.output)
  ) {
    throw new Error(
      "Brick: the client contract must be a separate schema module.",
    );
  }
  const name = app.client.exportName ?? "Api";
  const module = await (options.load
    ? options.load(modulePath)
    : import(pathToFileURL(modulePath).href));
  const api: unknown = module[name];
  if (!HttpApi.isHttpApi(api))
    throw new Error(
      `Brick: ${app.client.module} must export a HttpApi named '${name}'.`,
    );
  const expected = app.openApi();
  const actual = OpenApi.fromApi(api);
  if (
    !isDeepStrictEqual(expected.paths, actual.paths) ||
    !isDeepStrictEqual(expected.components, actual.components)
  ) {
    throw new Error(
      "Brick: the browser contract differs from the application's routes or schemas.",
    );
  }
  let specifier = relative(dirname(options.output), modulePath)
    .replaceAll("\\", "/")
    .replace(/\.(?:[cm]?ts|tsx)$/, "");
  if (!specifier.startsWith(".")) specifier = "./" + specifier;
  return `// Generated by Brick. Do not edit.
import { ${JSON.stringify(name)} as api } from ${JSON.stringify(specifier)};
import type { HttpApiClient } from "effect/http-api";
export { api };
export { createClient, createEffectClient } from "@brickkit/client";
export type AppClient = HttpApiClient.ForApi<typeof api>;
`;
}
