import { site } from "@/lib/site";

export type AccessPolicy = "public" | "authorized" | "scoped";

export interface ExampleAction {
  name: string;
  method?: string;
  path?: string;
  plugin?: string;
  resource?: string;
  description?: string;
  accessPolicy?: AccessPolicy;
  hasAuthorize?: boolean;
  emits?: string[];
  tags?: string[];
}

export interface ExampleTable {
  name: string;
  columns: {
    name: string;
    type: string;
    notNull: boolean;
    primary: boolean;
  }[];
}

export interface ExampleService {
  name: string;
  engine?: "sqlite" | "postgres";
  resources: string[];
  tables: ExampleTable[];
  actions: ExampleAction[];
}

/** One `examples/<slug>/brick.example.json` plus its generated architecture. */
export interface Example {
  slug: string;
  title: string;
  description: string;
  tags: string[];
  features: string[];
  entry: string;
  run: string[];
  runNote?: string;
  /** Optional hosted instance of the example. */
  demo?: string;
  order?: number;
  readme?: string;
  fileCount: number;
  architecture: { prefix: string; services: ExampleService[] };
}

export interface ExampleSource {
  path: string;
  lang: string;
  code: string;
}

// Generated by scripts/generate-examples.ts at build time.
const metadata = import.meta.glob<Example>("../generated/examples/*.json", {
  eager: true,
  import: "default",
});
const sources = import.meta.glob<ExampleSource[]>(
  "../generated/sources/*.json",
  { import: "default" },
);

const examples = Object.values(metadata).sort(
  (a, b) =>
    (a.order ?? Infinity) - (b.order ?? Infinity) ||
    a.title.localeCompare(b.title),
);

export const getExamples = () => examples;

export const getExample = (slug: string) =>
  examples.find((example) => example.slug === slug);

export function loadExampleSources(slug: string) {
  const load = sources[`../generated/sources/${slug}.json`];
  return load ? load() : Promise.resolve([]);
}

export const exampleGitHubUrl = (slug: string, path?: string) => {
  const kind = path ? "blob" : "tree";
  const suffix = path ? `/${path}` : "";
  return `${site.repo}/${kind}/main/examples/${slug}${suffix}`;
};

export const exampleCloneCommand = (slug: string) =>
  `git clone ${site.repo}.git && cd brick/examples/${slug}`;

export function exampleStats(example: Example) {
  const { services } = example.architecture;
  return {
    services: services.length,
    actions: services.reduce((sum, s) => sum + s.actions.length, 0),
    tables: services.reduce((sum, s) => sum + s.tables.length, 0),
  };
}
